"""Numeric Grounding Validator for Conversational Financial Responses.

Extracts all numerical quantities (amounts, totals, percentages, counts, years)
from the LLM generated response and verifies that every single number appears
in the verified Python tool output.

If any hallucinated or unverified number is detected, the validator flags a
violation, triggering an immediate fallback to the deterministic offline template.
"""

import re
from typing import Dict, Any, List, Set, Tuple, Optional


class NumericGroundingValidator:
    """Validator enforcing numeric factual grounding between tool outputs and LLM text."""

    # Matches integers, decimals, currency-prefixed, and comma-separated numbers
    _NUM_REGEX = re.compile(
        r"(?:₹|\$|€|£)?\b(\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?)\b%?",
        re.IGNORECASE
    )

    # Allowed conversational numbers (ranking, ordinals, singletons)
    ALLOWED_CONVERSATIONAL = {0.0, 1.0, 2.0, 3.0}

    @classmethod
    def extract_numbers_from_text(cls, text: str) -> List[float]:
        """Extract all numerical values from a text string."""
        if not text or not isinstance(text, str):
            return []

        nums = []
        for match in cls._NUM_REGEX.finditer(text):
            raw_val = match.group(1).replace(",", "")
            try:
                val = float(raw_val)
                nums.append(val)
            except ValueError:
                continue
        return nums

    @classmethod
    def extract_numbers_from_payload(cls, payload: Any) -> Set[float]:
        """Recursively extract all numeric facts from a tool payload."""
        allowed_nums: Set[float] = set()

        def _traverse(obj):
            if isinstance(obj, (int, float)):
                f_val = float(obj)
                allowed_nums.add(f_val)
                allowed_nums.add(round(f_val, 0))
                allowed_nums.add(round(f_val, 1))
                allowed_nums.add(round(f_val, 2))
                # If decimal probability / fraction, allow percentage representation
                if 0.0 <= f_val <= 1.0:
                    pct = f_val * 100.0
                    allowed_nums.add(pct)
                    allowed_nums.add(round(pct, 0))
                    allowed_nums.add(round(pct, 1))
                    allowed_nums.add(round(pct, 2))
            elif isinstance(obj, str):
                extracted = cls.extract_numbers_from_text(obj)
                for n in extracted:
                    allowed_nums.add(n)
                    allowed_nums.add(round(n, 0))
            elif isinstance(obj, dict):
                for k, v in obj.items():
                    # If key itself has numbers (e.g. '2024-10' or 'Lag 12')
                    for n in cls.extract_numbers_from_text(str(k)):
                        allowed_nums.add(n)
                    _traverse(v)
            elif isinstance(obj, (list, tuple, set)):
                for item in obj:
                    _traverse(item)

        _traverse(payload)
        return allowed_nums

    @classmethod
    def validate(
        cls,
        llm_reply: str,
        tool_payload: Dict[str, Any],
        tolerance: float = 0.5,
        allow_conversational: bool = True
    ) -> Tuple[bool, Optional[str]]:
        """Validate whether all numbers in the LLM reply are grounded in the tool payload.

        Args:
            llm_reply: Text string generated by LLM.
            tool_payload: Verified dictionary produced by Python financial tool.
            tolerance: Absolute numerical tolerance to accommodate rounding.
            allow_conversational: Whether to permit common list ordinals (1, 2, 3).

        Returns:
            Tuple of (is_valid: bool, failure_reason: Optional[str])
        """
        if not llm_reply or not isinstance(llm_reply, str):
            return True, None

        reply_numbers = cls.extract_numbers_from_text(llm_reply)
        if not reply_numbers:
            return True, None

        tool_numbers = cls.extract_numbers_from_payload(tool_payload)

        for num in reply_numbers:
            if allow_conversational and num in cls.ALLOWED_CONVERSATIONAL:
                continue

            # Check if num matches any tool number within tolerance
            is_matched = False
            for t_num in tool_numbers:
                if abs(num - t_num) <= tolerance:
                    is_matched = True
                    break
                # Also check relative tolerance for large amounts (e.g. ₹54,230 vs ₹54,200)
                if t_num != 0 and abs(num - t_num) / abs(t_num) < 0.01:
                    is_matched = True
                    break

            if not is_matched:
                return False, f"Unverified numerical fact '{num}' in reply not found in tool payload"

        return True, None
