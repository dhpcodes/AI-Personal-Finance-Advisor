class SyntheticDataGenerator:
    """
    Generates realistic synthetic multi-month transaction histories for backtesting forecasting models.
    All data generated by this module is clearly marked as SYNTHETIC.
    """

    @staticmethod
    def generate_persona_transactions(
        persona: str = "salaried_tech",
        num_months: int = 24,
        start_date: str = "2024-11-01",
        seed: int = 42
    ) -> pd.DataFrame:
        """
        Generates multi-month transaction history for backtesting.
        Personas supported:
        - 'salaried_tech': Regular salary, rent, EMIs, subscriptions, weekend spending, Diwali spike in Oct/Nov.
        - 'freelancer': Variable income, rent, utilities, variable entertainment and food spending.
        """
        rng = np.random.RandomState(seed)
        start_dt = pd.to_datetime(start_date)
        dates = pd.date_range(start=start_dt, periods=num_months, freq="MS")

        rows = []
        for i, dt in enumerate(dates):
            ym = dt.strftime("%Y-%m")
            month_idx = dt.month

            if persona == "salaried_tech":
                # 1. Salary Credit on 1st
                salary = 120000.0 + rng.uniform(-1000, 2000)
                rows.append({"date": f"{ym}-01", "transaction_description": "Salary Direct Deposit Infosys", "amount": salary, "category": "Income", "transaction_type": "income"})

                # 2. Rent on 2nd
                rows.append({"date": f"{ym}-02", "transaction_description": "Apartment Rent Payment Landlord", "amount": -32000.0, "category": "Rent", "transaction_type": "expense"})

                # 3. Car EMI on 5th
                rows.append({"date": f"{ym}-05", "transaction_description": "Auto Loan EMI HDFC Bank", "amount": -14500.0, "category": "Financial Services", "transaction_type": "expense"})

                # 4. Utilities on 10th
                util = 3500.0 + rng.uniform(-300, 500)
                rows.append({"date": f"{ym}-10", "transaction_description": "Electricity and Internet Bills", "amount": -util, "category": "Utilities & Services", "transaction_type": "expense"})

                # 5. Subscriptions on 15th
                rows.append({"date": f"{ym}-15", "transaction_description": "Netflix and Spotify Subscriptions", "amount": -1199.0, "category": "Entertainment & Recreation", "transaction_type": "expense"})

                # 6. Groceries & Dining (4 weekends)
                for w in range(4):
                    day = 7 * w + 3
                    groceries = 4000.0 + rng.uniform(-500, 800)
                    dining = 2500.0 + rng.uniform(-800, 1200)
                    rows.append({"date": f"{ym}-{day:02d}", "transaction_description": "Supermarket Grocery Order", "amount": -groceries, "category": "Food & Dining", "transaction_type": "expense"})
                    rows.append({"date": f"{ym}-{(day+1):02d}", "transaction_description": "Weekend Restaurant & Dining", "amount": -dining, "category": "Food & Dining", "transaction_type": "expense"})

                # 7. Shopping & Festival spikes (October/November Diwali / Festive Season)
                festive_mult = 3.5 if month_idx in [10, 11] else 1.0
                shopping = (6000.0 + rng.uniform(-1000, 2000)) * festive_mult
                rows.append({"date": f"{ym}-22", "transaction_description": "E-Commerce Shopping Festive Spree", "amount": -shopping, "category": "Shopping & Retail", "transaction_type": "expense"})

            else: # Freelancer
                # Variable income
                inc = rng.uniform(70000, 140000)
                rows.append({"date": f"{ym}-05", "transaction_description": "Client Project Milestone Payment", "amount": inc, "category": "Income", "transaction_type": "income"})
                rows.append({"date": f"{ym}-02", "transaction_description": "Studio Rent Payment", "amount": -25000.0, "category": "Rent", "transaction_type": "expense"})
                rows.append({"date": f"{ym}-12", "transaction_description": "Coworking Space Membership", "amount": -8500.0, "category": "Utilities & Services", "transaction_type": "expense"})
                food = rng.uniform(12000, 20000)
                rows.append({"date": f"{ym}-18", "transaction_description": "Monthly Cafe & Food Orders", "amount": -food, "category": "Food & Dining", "transaction_type": "expense"})
                travel = rng.uniform(4000, 12000)
                rows.append({"date": f"{ym}-25", "transaction_description": "Cab Rides & Travel Transit", "amount": -travel, "category": "Transportation", "transaction_type": "expense"})

        df = pd.DataFrame(rows)
        df["is_synthetic"] = True
        df["dataset_note"] = "SYNTHETIC: Generated for forecast backtesting and methodology validation."
        return df


class ForecastMetrics:
    """Evaluation metrics for time-series forecasting."""

    @staticmethod
    def smape(y_true: np.ndarray, y_pred: np.ndarray) -> float:
        """Symmetric Mean Absolute Percentage Error (sMAPE) in percentage."""
        denom = (np.abs(y_true) + np.abs(y_pred)) / 2.0
        mask = denom > 1e-6
        if not np.any(mask):
            return 0.0
        return float(np.mean(np.abs(y_true[mask] - y_pred[mask]) / denom[mask]) * 100.0)

    @staticmethod
    def mase(y_true: np.ndarray, y_pred: np.ndarray, y_train_history: np.ndarray) -> float:
        """Mean Absolute Scaled Error (MASE) relative to 1-step naive on history."""
        mae_model = np.mean(np.abs(y_true - y_pred))
        if len(y_train_history) <= 1:
            return 1.0
        mae_naive = np.mean(np.abs(np.diff(y_train_history)))
        if mae_naive < 1e-6:
            return float(mae_model)
        return float(mae_model / mae_naive)

    @staticmethod
    def mae(y_true: np.ndarray, y_pred: np.ndarray) -> float:
        return float(np.mean(np.abs(y_true - y_pred)))

    @staticmethod
    def rmse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
        return float(np.sqrt(np.mean((y_true - y_pred) ** 2)))


class BacktestEngine:
    """
    Rolling-origin time-series backtest engine.
    Compares baseline forecasting models against ground truth.
    """

    @staticmethod
    def run_rolling_origin_backtest(monthly_series: pd.Series, min_train_length: int = 6) -> pd.DataFrame:
        """
        Evaluates 1-step-ahead forecasts using an expanding rolling origin.
        Baselines:
        1. Last-Month Baseline (y_hat_t = y_{t-1})
        2. Moving-Average Baseline (3-month SMA)
        3. Seasonal-Naive Baseline (12-month lag if available, else last month)
        """
        n = len(monthly_series)
        if n < min_train_length + 2:
            raise ValueError(f"Monthly series too short ({n} months). Need at least {min_train_length + 2} months.")

        values = monthly_series.values
        months = monthly_series.index

        actuals = []
        preds_last = []
        preds_sma = []
        preds_seasonal = []

        for origin in range(min_train_length, n):
            train_hist = values[:origin]
            true_val = values[origin]

            # Baseline 1: Last Month
            y_hat_last = train_hist[-1]

            # Baseline 2: 3-month SMA
            k = min(3, len(train_hist))
            y_hat_sma = np.mean(train_hist[-k:])

            # Baseline 3: Seasonal-Naive (lag 12 if available, else lag 1)
            y_hat_seasonal = train_hist[-12] if len(train_hist) >= 12 else train_hist[-1]

            actuals.append(true_val)
            preds_last.append(y_hat_last)
            preds_sma.append(y_hat_sma)
            preds_seasonal.append(y_hat_seasonal)

        y_true = np.array(actuals)
        hist_all = values[:min_train_length]

        models = {
            "Last-Month Naive": np.array(preds_last),
            "Moving-Average (3-Month SMA)": np.array(preds_sma),
            "Seasonal-Naive (12-Month Lag)": np.array(preds_seasonal)
        }

        report_rows = []
        for name, y_pred in models.items():
            report_rows.append({
                "Forecasting_Model": name,
                "Backtest_Method": "Rolling-Origin Expanding Window",
                "Evaluation_Windows": len(y_true),
                "MAE": round(ForecastMetrics.mae(y_true, y_pred), 2),
                "RMSE": round(ForecastMetrics.rmse(y_true, y_pred), 2),
                "sMAPE (%)": round(ForecastMetrics.smape(y_true, y_pred), 2),
                "MASE": round(ForecastMetrics.mase(y_true, y_pred, hist_all), 3),
                "Model_Type": "Deterministic Baseline"
            })

        return pd.DataFrame(report_rows)


class PersonalizedSpendingForecaster:
    """
    Runtime forecaster operating on an individual user's dated monthly transaction history.
    Strictly distinguishes actual historical spending from estimated future spending.
    """

    @staticmethod
    def forecast_user_expenses(df: pd.DataFrame) -> Dict[str, Any]:
        """
        Computes 1-month-ahead expense forecast from user's dated transaction history.
        Fails safely if insufficient history exists (< 3 months).
        """
        if df is None or len(df) == 0 or "amount" not in df.columns:
            return {
                "status": "insufficient_data",
                "message": "Not enough historical data for a reliable forecast. Requires at least 3 months of dated transactions."
            }

        work_df = df.copy()
        work_df["amount"] = pd.to_numeric(work_df["amount"], errors="coerce").fillna(0.0)

        if "date" not in work_df.columns:
            return {
                "status": "insufficient_data",
                "message": "Not enough historical data for a reliable forecast (missing 'date' column)."
            }

        work_df["YearMonth"] = pd.to_datetime(work_df["date"], errors="coerce").dt.strftime("%Y-%m")
        work_df = work_df.dropna(subset=["YearMonth"])

        cat_col = "category" if "category" in work_df.columns else "predicted_category"
        if cat_col in work_df.columns:
            work_df = work_df[work_df[cat_col].str.lower() != "income"].copy()

        # Monthly total expenses
        monthly_exp = work_df.groupby("YearMonth")["amount"].apply(lambda s: s.apply(abs).sum()).sort_index()

        if len(monthly_exp) < 3:
            return {
                "status": "insufficient_data",
                "message": f"Not enough historical data for a reliable forecast. Recorded {len(monthly_exp)} month(s); minimum 3 months required."
            }

        history_values = monthly_exp.values
        recent_3 = history_values[-3:]
        # Baseline forecast: Weighted moving average (gives higher weight to recent months)
        weights = np.array([0.2, 0.3, 0.5])
        point_forecast = float(round(np.sum(recent_3 * weights), 2))

        # Empirical volatility / uncertainty range (standard deviation of recent history)
        volatility = float(np.std(recent_3)) if len(recent_3) > 1 else point_forecast * 0.10
        lower_bound = max(0.0, float(round(point_forecast - 1.28 * volatility, 2))) # approx 80% empirical interval
        upper_bound = float(round(point_forecast + 1.28 * volatility, 2))

        # Category-level breakdown based on recent 3-month distribution
        recent_months = monthly_exp.index[-3:]
        recent_txns = work_df[work_df["YearMonth"].isin(recent_months)]
        cat_breakdown = {}
        if cat_col in recent_txns.columns and len(recent_txns) > 0:
            cat_totals = recent_txns.groupby(cat_col)["amount"].apply(lambda s: s.apply(abs).sum())
            total_recent = cat_totals.sum()
            if total_recent > 0:
                for cat, amt in cat_totals.items():
                    share = amt / total_recent
                    cat_breakdown[cat] = float(round(point_forecast * share, 2))

        explanation = (
            f"Your next-month estimated spending of ₹{point_forecast:,.2f} is derived from a 3-month weighted "
            f"moving average of your recent spending (avg ₹{float(np.mean(recent_3)):,.2f}/mo), "
            f"with an empirical forecast range of ₹{lower_bound:,.2f} – ₹{upper_bound:,.2f}."
        )

        return {
            "status": "success",
            "historical_months_count": len(monthly_exp),
            "historical_monthly_spending": monthly_exp.to_dict(),
            "point_forecast": point_forecast,
            "lower_bound": lower_bound,
            "upper_bound": upper_bound,
            "category_forecast": cat_breakdown,
            "method": "3-Month Weighted Moving Average with Empirical Volatility Bounds",
            "explanation": explanation
        }


# Convenience alias for application and tests
SpendingForecaster = PersonalizedSpendingForecaster

